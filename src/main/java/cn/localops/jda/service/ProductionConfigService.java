package cn.localops.jda.service;

import cn.localops.jda.model.ProductionRuntimeConfig;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public final class ProductionConfigService {
    private static final DateTimeFormatter BACKUP_TIME = DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss-SSS");
    private static final Pattern SHORT_DATABASE_ADDRESS = Pattern.compile("^[A-Za-z0-9.-]+:(\\d{1,5})$");
    private static final Pattern JDBC_TEMPLATE = Pattern.compile(
            "^(jdbc:[A-Za-z0-9][A-Za-z0-9+.-]*://)([^/;?\\s]+)(.*)$");

    public String normalizeDatabaseUrl(String input, String detectedJdbcUrl) {
        requireSingleLine(input, "数据库连接地址");
        String entered = input.strip();
        if (entered.startsWith("jdbc:")) {
            return entered;
        }

        Matcher shortAddress = SHORT_DATABASE_ADDRESS.matcher(entered);
        if (!shortAddress.matches()) {
            throw new IllegalArgumentException("数据库地址可以填写完整 JDBC，或填写 IP:端口并复用源码中的数据库名。");
        }
        int port = Integer.parseInt(shortAddress.group(1));
        if (port < 1 || port > 65_535) {
            throw new IllegalArgumentException("数据库端口必须在 1 到 65535 之间。");
        }

        String template = detectedJdbcUrl == null ? "" : detectedJdbcUrl.strip();
        Matcher jdbc = JDBC_TEMPLATE.matcher(template);
        if (!jdbc.matches()) {
            throw new IllegalArgumentException("源码中未识别到数据库类型和库名，请填写完整 JDBC 地址。");
        }
        return jdbc.group(1) + entered + jdbc.group(3);
    }

    public void validate(ProductionRuntimeConfig config) {
        if (config == null) {
            throw new IllegalArgumentException("请填写生产环境配置。");
        }
        requireSingleLine(config.databaseUrl(), "数据库连接地址");
        if (!config.databaseUrl().strip().startsWith("jdbc:")) {
            throw new IllegalArgumentException("数据库连接地址必须是以 jdbc: 开头的 JDBC 地址。");
        }
        requireSingleLine(config.databaseUsername(), "数据库用户名");
        requireSingleLine(config.databasePassword(), "数据库密码");
        if (!config.jwtSecret().isBlank()) {
            requireSingleLine(config.jwtSecret(), "JWT 密钥");
        }
    }

    public Path write(Path productionRoot, int backendPort, ProductionRuntimeConfig config) throws IOException {
        validate(config);
        if (productionRoot == null || !productionRoot.isAbsolute()) {
            throw new IllegalArgumentException("生产根目录必须是绝对路径。");
        }
        if (backendPort < 1 || backendPort > 65_535) {
            throw new IllegalArgumentException("后端端口必须在 1 到 65535 之间。");
        }

        Path root = productionRoot.toAbsolutePath().normalize();
        Path configDirectory = root.resolve("backend").resolve("config");
        Path target = configDirectory.resolve("application-prod.yml");
        Files.createDirectories(configDirectory);
        backupExisting(root, target);

        String jwtSection = config.jwtSecret().isBlank()
                ? ""
                : "jwt:\n  secret: " + yamlString(config.jwtSecret()) + "\n";
        String yaml = """
                # Generated by Jenkins一键部署助手. Keep this file outside source control.
                spring:
                  datasource:
                    url: %s
                    username: %s
                    password: %s
                %sserver:
                  port: %d
                """.formatted(
                yamlString(config.databaseUrl().strip()),
                yamlString(config.databaseUsername().strip()),
                yamlString(config.databasePassword()),
                jwtSection,
                backendPort);

        Path temporary = Files.createTempFile(configDirectory, "application-prod-", ".tmp");
        try {
            Files.writeString(temporary, yaml, StandardCharsets.UTF_8);
            moveAtomically(temporary, target);
        } finally {
            Files.deleteIfExists(temporary);
        }
        return target;
    }

    private static void backupExisting(Path root, Path target) throws IOException {
        if (!Files.isRegularFile(target)) {
            return;
        }
        Path backupDirectory = root.resolve("backups").resolve("config");
        Files.createDirectories(backupDirectory);
        Path backup = backupDirectory.resolve("application-prod-" + BACKUP_TIME.format(LocalDateTime.now()) + ".yml");
        Files.copy(target, backup, StandardCopyOption.COPY_ATTRIBUTES);
    }

    private static void moveAtomically(Path source, Path target) throws IOException {
        try {
            Files.move(source, target, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
        } catch (AtomicMoveNotSupportedException exception) {
            Files.move(source, target, StandardCopyOption.REPLACE_EXISTING);
        }
    }

    private static String yamlString(String value) {
        return "'" + value.replace("'", "''") + "'";
    }

    private static void requireSingleLine(String value, String label) {
        if (value == null || value.isBlank()) {
            throw new IllegalArgumentException(label + "不能为空。");
        }
        if (value.indexOf('\r') >= 0 || value.indexOf('\n') >= 0 || value.indexOf('\0') >= 0) {
            throw new IllegalArgumentException(label + "不能包含换行符或控制字符。");
        }
    }
}
